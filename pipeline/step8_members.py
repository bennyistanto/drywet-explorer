"""Step 8: which drawn cells belong to each unit, for the page.

The map modes "How long", "Status" and "Pattern" are stored per cell. For the panels under the map to follow
the mode, the page has to know a unit's cells, under the same ALL TOUCHED rule the pipeline uses everywhere
(every land cell the unit's polygon intersects, at full area). Storing per-unit tables of those modes for
7,298 kecamatan and 912 months would cost far more than the site can carry; a list of cells per unit costs
almost nothing, and the page then sums cell areas for the unit it is showing.

This is the same membership step 1 uses: pipeline.step1_classes.weights_matrix on step 0's weights files.

Writes:
  site/data/members/adm{1,2,3}.u32.gz   uint32: N, then N + 1 offsets, then the drawn-cell positions of unit 1, unit 2, ...
                                        (unit ids are 1..N in the order of the unit tables)
  site/data/cell_area.f32.gz            float32 km2 of every drawn cell
  site/data/members_files.js            generated: one literal FileAttachment per file
  data/step8/manifest.json

Run from the repository root:  python -m pipeline.step8_members   (seconds; reads no index file)
"""
import json
from datetime import datetime

import numpy as np
import pandas as pd
import xarray as xr

from . import config as C
from .step1_classes import weights_matrix
from .step3_export import gz_write


def main():
    grid = xr.open_dataset(C.STEP0 / "grid.nc")
    ny, nx = grid["cell_area_km2"].shape
    cell_area = grid["cell_area_km2"].values.astype(np.float64).ravel()
    grid.close()
    drawn = np.fromfile(C.STEP1 / "maps" / "cells.u32", "<u4").astype(np.int64)
    pos_of_cell = np.full(ny * nx, -1, np.int64)
    pos_of_cell[drawn] = np.arange(len(drawn))
    out = C.SITE_DATA / "members"
    sizes = {"cell_area.f32.gz": gz_write(C.SITE_DATA / "cell_area.f32.gz", cell_area[drawn].astype("<f4").tobytes())}
    stats = {}
    for n in (1, 2, 3):
        units = pd.read_csv(C.STEP0 / f"units_adm{n}.csv", dtype={"code": str})
        assert (units["id"].to_numpy() == np.arange(1, len(units) + 1)).all()
        wf = np.load(C.STEP0 / f"weights_adm{n}.npz")
        W = weights_matrix(wf["cell"], wf["unit"], pos_of_cell, cell_area, len(units)).tocsr()
        W.sum_duplicates()
        W.sort_indices()
        total = np.asarray(W.sum(axis=1)).ravel()
        assert np.allclose(total, units["cells_km2"].to_numpy(), atol=0.01), f"adm{n}: cell area differs from the unit table"
        assert (np.diff(W.indptr) == units["n_cells"].to_numpy()).all(), f"adm{n}: cell counts differ from the unit table"
        blob = np.concatenate([np.array([len(units)], "<u4"), W.indptr.astype("<u4"), W.indices.astype("<u4")])
        sizes[f"members/adm{n}.u32.gz"] = gz_write(out / f"adm{n}.u32.gz", blob.tobytes())
        stats[f"adm{n}"] = dict(units=int(len(units)), pairs=int(W.nnz), bytes=sizes[f"members/adm{n}.u32.gz"])
        print(f"adm{n}: {len(units)} units, {W.nnz:,} unit-cell pairs, {sizes[f'members/adm{n}.u32.gz'] / 1e6:.2f} MB")
    lines = ["// Generated by pipeline/step8_members.py. Do not edit.", 'import {FileAttachment} from "observablehq:stdlib";',
             "export const membersFiles = {", '  cellArea: FileAttachment("cell_area.f32.gz"),',
             '  adm1: FileAttachment("members/adm1.u32.gz"),', '  adm2: FileAttachment("members/adm2.u32.gz"),',
             '  adm3: FileAttachment("members/adm3.u32.gz")', "};", ""]
    (C.SITE_DATA / "members_files.js").write_text("\n".join(lines), encoding="utf-8")
    (C.OUT / "step8").mkdir(parents=True, exist_ok=True)
    (C.OUT / "step8" / "manifest.json").write_text(json.dumps(dict(
        created=datetime.now().isoformat(timespec="seconds"), n_drawn=int(len(drawn)),
        rule="all touched: every land cell a unit's polygon intersects, at full cell area", levels=stats, bytes=sizes), indent=1), encoding="utf-8")


if __name__ == "__main__":
    main()
